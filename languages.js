/**
 * Global Language Switcher Logic
 */
let currentLang = 'uz';

function changeLanguage(langKey) {
  if (!translations[langKey]) return;

  currentLang = langKey;
  localStorage.setItem('islamic_app_lang', langKey);

  // Set HTML direction for Arabic (RTL) vs others (LTR)
  const htmlElem = document.documentElement;
  if (langKey === 'ar') {
    htmlElem.setAttribute('dir', 'rtl');
    htmlElem.setAttribute('lang', 'ar');
  } else {
    htmlElem.setAttribute('dir', 'ltr');
    htmlElem.setAttribute('lang', langKey);
  }

  // Translate elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[langKey][key]) {
      element.textContent = translations[langKey][key];
    }
  });

  // Translate placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const key = element.getAttribute('data-i18n-placeholder');
    if (translations[langKey][key]) {
      element.placeholder = translations[langKey][key];
    }
  });

  // Update language select dropdown value
  const langSelect = document.getElementById('languageSelect');
  if (langSelect) langSelect.value = langKey;
}

/**
 * Smart Auto Language Detection based on User Geolocation/IP & Browser
 */
async function autoDetectLanguage() {
  const savedLang = localStorage.getItem('islamic_app_lang');
  if (savedLang && translations[savedLang]) {
    changeLanguage(savedLang);
    return;
  }

  try {
    // GeoIP Detection
    const res = await fetch('https://ipapi.co/json/');
    const data = await res.json();
    const country = data.country_code;

    if (country === 'UZ') changeLanguage('uz');
    else if (country === 'KG') changeLanguage('ky');
    else if (country === 'RU' || country === 'BY' || country === 'KZ') changeLanguage('ru');
    else if (['SA', 'AE', 'EG', 'TR', 'QA', 'KW'].includes(country)) changeLanguage('ar');
    else {
      // Browser Language Fallback
      const browserLang = navigator.language.slice(0, 2);
      if (translations[browserLang]) {
        changeLanguage(browserLang);
      } else {
        changeLanguage('en');
      }
    }
  } catch (error) {
    // Default fallback to Uzbek
    changeLanguage('uz');
  }
}